"""Exact small-lattice helpers for toric-code observable contrast.

The routines use the tensor product of link Hilbert spaces.  In gauge-theory
language this is the extended-link (electric-center) prescription, not a
claim that a physical gauge Hilbert space factorizes uniquely by region.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass

import numpy as np
from numpy.typing import ArrayLike, NDArray

ComplexMatrix = NDArray[np.complex128]
ComplexVector = NDArray[np.complex128]


def _validate_eigenvalue(value: int, name: str) -> int:
    output = int(value)
    if output not in (-1, 1):
        raise ValueError(f"{name} must be +1 or -1.")
    return output


@dataclass(frozen=True)
class ToricCodeLattice:
    """Periodic square lattice with one qubit on every oriented link."""

    size: int

    def __post_init__(self) -> None:
        if self.size < 2:
            raise ValueError("The periodic lattice size must be at least two.")

    @property
    def num_qubits(self) -> int:
        return 2 * self.size**2

    def horizontal_edge(self, x: int, y: int) -> int:
        """Link from ``(x, y)`` to ``(x + 1, y)``."""

        size = self.size
        return (y % size) * size + (x % size)

    def vertical_edge(self, x: int, y: int) -> int:
        """Link from ``(x, y)`` to ``(x, y + 1)``."""

        size = self.size
        return size**2 + (y % size) * size + (x % size)

    def star_edges(self, x: int, y: int) -> tuple[int, ...]:
        return (
            self.horizontal_edge(x, y),
            self.horizontal_edge(x - 1, y),
            self.vertical_edge(x, y),
            self.vertical_edge(x, y - 1),
        )

    def plaquette_edges(self, x: int, y: int) -> tuple[int, ...]:
        return (
            self.horizontal_edge(x, y),
            self.vertical_edge(x + 1, y),
            self.horizontal_edge(x, y + 1),
            self.vertical_edge(x, y),
        )

    def logical_z_x_edges(self, *, row: int = 0) -> tuple[int, ...]:
        """Horizontal noncontractible primal loop."""

        return tuple(self.horizontal_edge(x, row) for x in range(self.size))

    def logical_z_y_edges(self, *, column: int = 0) -> tuple[int, ...]:
        """Vertical noncontractible primal loop."""

        return tuple(self.vertical_edge(column, y) for y in range(self.size))

    def logical_x_x_edges(self, *, column: int = 0) -> tuple[int, ...]:
        """Dual loop that flips the horizontal logical-Z eigenvalue."""

        return tuple(self.horizontal_edge(column, y) for y in range(self.size))

    def logical_x_y_edges(self, *, row: int = 0) -> tuple[int, ...]:
        """Dual loop that flips the vertical logical-Z eigenvalue."""

        return tuple(self.vertical_edge(x, row) for x in range(self.size))

    def all_stars(self) -> tuple[tuple[int, ...], ...]:
        return tuple(
            self.star_edges(x, y) for y in range(self.size) for x in range(self.size)
        )

    def all_plaquettes(self) -> tuple[tuple[int, ...], ...]:
        return tuple(
            self.plaquette_edges(x, y)
            for y in range(self.size)
            for x in range(self.size)
        )


def qubit_mask(qubits: Iterable[int]) -> int:
    """Return an integer bit mask, rejecting repeated/negative qubits."""

    output = 0
    for item in qubits:
        qubit = int(item)
        if qubit < 0:
            raise ValueError("Qubit indices must be nonnegative.")
        bit = 1 << qubit
        if output & bit:
            raise ValueError("Qubit indices must be unique.")
        output |= bit
    return output


def star_group_support(lattice: ToricCodeLattice) -> NDArray[np.int64]:
    """Computational-basis support generated by the independent star group."""

    generators = [qubit_mask(edges) for edges in lattice.all_stars()[:-1]]
    support = {0}
    for generator in generators:
        support |= {basis ^ generator for basis in tuple(support)}
    return np.asarray(sorted(support), dtype=np.int64)


def toric_code_ground_state(
    lattice: ToricCodeLattice,
    *,
    logical_z_x: int = 1,
    logical_z_y: int = 1,
    max_qubits: int = 22,
) -> ComplexVector:
    """Construct an exact fixed-point ground state in a logical-Z sector.

    The dense return value is intentional for the small exact benchmark.
    ``max_qubits`` prevents accidental exponential allocations.
    """

    logical_z_x = _validate_eigenvalue(logical_z_x, "logical_z_x")
    logical_z_y = _validate_eigenvalue(logical_z_y, "logical_z_y")
    if lattice.num_qubits > max_qubits:
        raise ValueError(
            f"Dense construction is limited to {max_qubits} qubits; "
            "use a stabilizer or tensor-network representation instead."
        )
    seed = 0
    if logical_z_x == -1:
        seed ^= qubit_mask(lattice.logical_x_x_edges())
    if logical_z_y == -1:
        seed ^= qubit_mask(lattice.logical_x_y_edges())
    support = star_group_support(lattice) ^ seed
    state = np.zeros(1 << lattice.num_qubits, dtype=np.complex128)
    state[support] = 1.0 / np.sqrt(len(support))
    return state


def reduced_density_on_qubits(
    state: ArrayLike,
    kept_qubits: Sequence[int],
    *,
    tolerance: float = 1e-14,
) -> ComplexMatrix:
    """Partial trace of a pure state, preserving the given qubit order."""

    vector = np.asarray(state, dtype=np.complex128)
    if vector.ndim != 1 or len(vector) == 0 or len(vector) & (len(vector) - 1):
        raise ValueError("state must be a power-of-two one-dimensional vector.")
    num_qubits = len(vector).bit_length() - 1
    kept = tuple(int(item) for item in kept_qubits)
    if len(set(kept)) != len(kept):
        raise ValueError("kept_qubits must not contain duplicates.")
    if any(item < 0 or item >= num_qubits for item in kept):
        raise ValueError("A kept qubit lies outside the state.")
    environment = tuple(item for item in range(num_qubits) if item not in kept)
    support = np.flatnonzero(np.abs(vector) > tolerance).astype(np.int64)
    kept_index = np.zeros(len(support), dtype=np.int64)
    environment_index = np.zeros(len(support), dtype=np.int64)
    for output_bit, input_bit in enumerate(kept):
        kept_index |= ((support >> input_bit) & 1) << output_bit
    for output_bit, input_bit in enumerate(environment):
        environment_index |= ((support >> input_bit) & 1) << output_bit
    amplitudes = np.zeros(
        (1 << len(environment), 1 << len(kept)),
        dtype=np.complex128,
    )
    amplitudes[environment_index, kept_index] = vector[support]
    density = amplitudes.T @ amplitudes.conj()
    return 0.5 * (density + density.conj().T)


def pauli_string_expectation(
    state: ArrayLike,
    paulis: Mapping[int, str],
    *,
    support: ArrayLike | None = None,
    tolerance: float = 1e-14,
) -> complex:
    """Expectation of a sparse Pauli string on a pure state."""

    vector = np.asarray(state, dtype=np.complex128)
    if vector.ndim != 1 or len(vector) == 0 or len(vector) & (len(vector) - 1):
        raise ValueError("state must be a power-of-two one-dimensional vector.")
    num_qubits = len(vector).bit_length() - 1
    x_mask = 0
    z_mask = 0
    num_y = 0
    for raw_qubit, raw_operator in paulis.items():
        qubit = int(raw_qubit)
        operator = str(raw_operator).upper()
        if qubit < 0 or qubit >= num_qubits:
            raise ValueError("A Pauli qubit lies outside the state.")
        if operator not in {"I", "X", "Y", "Z"}:
            raise ValueError("Pauli operators must be I, X, Y, or Z.")
        if operator in {"X", "Y"}:
            x_mask |= 1 << qubit
        if operator in {"Z", "Y"}:
            z_mask |= 1 << qubit
        if operator == "Y":
            num_y += 1
    if support is None:
        basis = np.flatnonzero(np.abs(vector) > tolerance).astype(np.int64)
    else:
        basis = np.asarray(support, dtype=np.int64)
        if basis.ndim != 1:
            raise ValueError("support must be one-dimensional.")
    signs = np.fromiter(
        (-1.0 if (int(item) & z_mask).bit_count() % 2 else 1.0 for item in basis),
        dtype=np.float64,
        count=len(basis),
    )
    phases = (1j**num_y) * signs
    targets = basis ^ x_mask
    return complex(np.vdot(vector[targets], phases * vector[basis]))


def z_parity_projectors(
    num_qubits: int,
) -> tuple[ComplexMatrix, ComplexMatrix]:
    """Projectors onto even (+1) and odd (-1) tensor-Z parity."""

    if num_qubits < 1:
        raise ValueError("num_qubits must be positive.")
    dimension = 1 << num_qubits
    parities = np.fromiter(
        (int(index).bit_count() % 2 for index in range(dimension)),
        dtype=np.int8,
        count=dimension,
    )
    even = np.diag((parities == 0).astype(np.complex128))
    odd = np.diag((parities == 1).astype(np.complex128))
    return even, odd


def parity_sector_state(num_qubits: int, eigenvalue: int) -> ComplexMatrix:
    """Maximally mixed state in a tensor-Z parity sector."""

    eigenvalue = _validate_eigenvalue(eigenvalue, "eigenvalue")
    even, odd = z_parity_projectors(num_qubits)
    projector = even if eigenvalue == 1 else odd
    return projector / np.trace(projector)


def even_parity_flip_unitaries(
    num_qubits: int,
) -> tuple[ComplexMatrix, ...]:
    """Permutation representation of all even-weight bit flips."""

    if num_qubits < 1:
        raise ValueError("num_qubits must be positive.")
    dimension = 1 << num_qubits
    basis = np.arange(dimension)
    output = []
    for mask in range(dimension):
        if mask.bit_count() % 2:
            continue
        unitary = np.zeros((dimension, dimension), dtype=np.complex128)
        unitary[basis ^ mask, basis] = 1.0
        output.append(unitary)
    return tuple(output)


def binary_measurement_success(
    effect: ArrayLike,
    positive_state: ArrayLike,
    negative_state: ArrayLike,
) -> float:
    """Equal-prior success when ``effect`` means the positive hypothesis."""

    measurement = np.asarray(effect, dtype=np.complex128)
    positive = np.asarray(positive_state, dtype=np.complex128)
    negative = np.asarray(negative_state, dtype=np.complex128)
    if (
        measurement.ndim != 2
        or measurement.shape[0] != measurement.shape[1]
        or positive.shape != measurement.shape
        or negative.shape != measurement.shape
    ):
        raise ValueError("effect and both states must be equal square matrices.")
    identity = np.eye(len(measurement), dtype=np.complex128)
    value = 0.5 * (
        np.trace(measurement @ positive) + np.trace((identity - measurement) @ negative)
    )
    return float(np.real(value))
